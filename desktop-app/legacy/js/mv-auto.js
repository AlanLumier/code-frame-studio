/* ==========================================================================
   Code MV · 离线「一键 MV」生成器（不需要任何 AI 接口）
   --------------------------------------------------------------------------
   思路（参考 ClaudeAnimationBase 的「先分镜、再逐镜成片」工作流）：
   1. 读歌词 → 按关键词归类到 7 种画面母题（夜 / 水 / 风 / 城市 / 光 / 自然 / 记忆）
   2. 每句歌词一个镜头，句间做 0.4s 交叉淡出
   3. 画面元素跟鼓点/低音联动（f.pulse / f.bass），镜头持续缓慢推进
   4. 输出确定性的 Canvas 代码，交给现有 SceneCore 沙箱执行/导出
   ========================================================================== */

window.CodeMV = window.CodeMV || {};

(function (NS) {
  "use strict";

  var MOTIFS = [
    { id: "pal", re: /(你|陪|一起|取代|灰暗|阴霾|笑|温暖|日子|发抖|学会|记得|拥抱)/ },
    { id: "sea", re: /(海|潮|浪|月|跨越|远方|彼岸)/ },
    { id: "night", re: /(夜|月|星|晚|黑|天空|梦)/ },
    { id: "water", re: /(海|潮|浪|水|雨|泪|河|湖|淹没|涌)/ },
    { id: "wind", re: /(风|云|飞|飘|吹|远|走|离开)/ },
    { id: "city", re: /(城|街|楼|灯|窗|路|车|人海|呼吸)/ },
    { id: "light", re: /(光|火|暖|阳|亮|燃烧|灯)/ },
    { id: "nature", re: /(花|树|叶|森|山|草|春|夏|秋|冬)/ },
    { id: "memory", re: /(名字|记得|忘记|时间|从前|回忆|故事|永远)/ }
  ];

  function motifFor(text) {
    for (var i = 0; i < MOTIFS.length; i++) {
      if (MOTIFS[i].re.test(text || "")) return MOTIFS[i].id;
    }
    return "city";
  }

  function build(lines, duration) {
    var motifs = (lines || []).map(function (l) {
      return motifFor(l.text);
    });
    var payload = JSON.stringify({
      motifs: motifs,
      texts: (lines || []).map(function (l) { return l.text || ""; }),
      duration: duration || 24
    });

    return [
      "// 由 Code MV 离线生成 · 逐句画面 + 卡点 + 镜头推进（无需 AI）",
      "var W = f.W, H = f.H, t = f.t, pal = f.pal;",
      "var M = " + payload + ";",
      "var motifs = M.motifs;",
      "var texts = M.texts || [];",
      "var line = f.line;",
      "var idx = line ? line.index : 0;",
      "var lp = line ? f.clamp(line.age / Math.max(0.5, line.dur), 0, 1) : 1;",
      "var pulse = f.pulse(), bass = f.bass, energy = f.energy;",
      "var breath = 1 + Math.sin(t * 0.55) * 0.008;",
      "var cam = { x: Math.sin(t * 0.1) * W * 0.008, y: Math.cos(t * 0.09) * H * 0.005 };",
      "function bg(col, glowCol) {",
      "  f.fill(col);",
      "  f.glow(W * 0.5, H * 0.42, W * (0.55 + 0.05 * pulse), glowCol, 0.12 + energy * 0.08);",
      "  f.vignette(0.55 - 0.06 * pulse);",
      "}",
      "function night(a) {",
      "  bg([6, 8, 22], pal.primary);",
      "  for (var i = 0; i < 50; i++) f.circle(f.hash(i * 3.1) * W, f.hash(i * 7.7) * H * 0.55, 0.7 + f.hash(i) * 1.2, pal.light, 0.12 + 0.3 * Math.abs(Math.sin(t + i)));",
      "  var mx = W * 0.72 + cam.x, my = H * 0.22 + cam.y;",
      "  f.glow(mx, my, H * 0.16, pal.light, 0.32);",
      "  f.circle(mx, my, H * 0.05 * breath, [246, 248, 255], a);",
      "}",
      "function water(a) {",
      "  bg([4, 10, 24], pal.light);",
      "  f.glow(W * 0.5, H * 0.24, H * 0.2, pal.light, 0.3);",
      "  f.circle(W * 0.5, H * 0.24, H * 0.05, [246, 248, 255], a);",
      "  for (var w = 0; w < 4; w++) {",
      "    var yy = H * (0.55 + w * 0.1) + Math.sin(t * (1 + w * 0.2)) * H * 0.006;",
      "    ctx.beginPath(); ctx.moveTo(0, yy);",
      "    for (var x = 0; x <= W; x += W / 24) ctx.lineTo(x, yy + Math.sin(x / W * 5 + t * (1.2 + w * 0.2) + w) * H * 0.02);",
      "    ctx.strokeStyle = f.rgb(pal.light, (0.28 - w * 0.05) * a); ctx.lineWidth = H * 0.006; ctx.stroke();",
      "  }",
      "}",
      "function wind(a) {",
      "  bg([10, 14, 18], pal.accent);",
      "  for (var i = 0; i < 6; i++) {",
      "    ctx.beginPath();",
      "    for (var x = 0; x <= W; x += W / 20) {",
      "      var y = H * (0.14 + i * 0.13) + Math.sin(x / W * 4 + t * 1.3 + i) * H * 0.03;",
      "      if (x === 0) ctx.moveTo(x, y); else ctx.lineTo(x, y);",
      "    }",
      "    ctx.strokeStyle = f.rgb(pal.accent, 0.12 * a); ctx.lineWidth = 1.5; ctx.stroke();",
      "  }",
      "  for (var p2 = 0; p2 < 8; p2++) {",
      "    var px = (f.hash(p2 * 3.3) * W + t * (40 + f.hash(p2) * 55)) % W;",
      "    var py = H * (0.2 + f.hash(p2 * 7.7) * 0.55) + Math.sin(t * 2 + p2) * H * 0.03;",
      "    f.rect(px, py, W * 0.012, H * 0.014, pal.light, 0.45 * a);",
      "  }",
      "}",
      "function city(a) {",
      "  bg([6, 10, 18], pal.primary);",
      "  for (var i = 0; i < 9; i++) {",
      "    var bx = W * (0.06 + i * 0.11), bh = H * (0.18 + f.hash(i * 5.3) * 0.42);",
      "    f.rect(bx, H * 0.78 - bh, W * 0.075, bh, [14, 18, 30], a);",
      "    f.rect(bx + W * 0.015, H * 0.74 - bh * 0.5, W * 0.012, H * 0.01, pal.accent, 0.5 * Math.abs(Math.sin(t + i)));",
      "  }",
      "  f.glow(W * 0.5, H * 0.5, W * 0.5, pal.primary, (0.1 + 0.05 * Math.sin(t * 1.2)) * a);",
      "}",
      "function light(a) {",
      "  bg([12, 9, 8], pal.accent);",
      "  var lx = W * 0.5 + cam.x * 2, ly = H * 0.35 + cam.y;",
      "  f.glow(lx, ly, H * (0.4 + 0.06 * pulse), pal.accent, 0.35 + bass * 0.15);",
      "  f.circle(lx, ly, H * 0.06 * breath * (1 + bass * 0.06), [255, 240, 220], a);",
      "  for (var i = 0; i < 5; i++) f.line(lx, ly, lx + Math.sin(i * 2.2 + t) * W * 0.3, ly + H * 0.3, pal.accent, 2, 0.08 * a);",
      "}",
      "function nature(a) {",
      "  bg([8, 16, 10], pal.primary);",
      "  for (var i = 0; i < 7; i++) {",
      "    var bx = W * (0.1 + i * 0.13), h2 = H * (0.2 + f.hash(i * 4.7) * 0.3);",
      "    f.line(bx, H * 0.78, bx + Math.sin(t + i) * W * 0.01, H * 0.78 - h2, [30, 50, 30], W * 0.006, a);",
      "    for (var k = 0; k < 5; k++) f.ellipse(bx + (f.hash(i * 9 + k) - 0.5) * W * 0.08, H * 0.78 - h2 + k * H * 0.05, W * 0.02, H * 0.012, [60, 120, 70], 0.5 * a);",
      "  }",
      "}",
      "function memory(a) {",
      "  bg([10, 10, 16], pal.light);",
      "  for (var i = 0; i < 24; i++) {",
      "    var x = f.hash(i * 3.7) * W, y = f.hash(i * 8.1) * H;",
      "    var k = (t * 0.1 + f.hash(i)) % 1;",
      "    f.circle(x + Math.sin(t + i) * W * 0.01, y - k * H * 0.1, 1 + f.hash(i * 2) * 2, pal.light, (1 - k) * 0.25 * a);",
      "  }",
      "  f.text('· · ·', W * 0.5, H * 0.55, { size: H * 0.05, color: pal.accent, alpha: 0.25 * a, align: 'center' });",
      "}",
      "function pal(a) {",
      "  var txt = texts[idx] || '';",
      "  var sad = /(灰暗|阴霾|雨|冷|寒|发抖|哭|别离|离开)/.test(txt);",
      "  var happy = /(笑|开心|温暖|陪伴|一起|取代|学会)/.test(txt);",
      "  var skyTop = sad ? [150, 156, 168] : happy ? [138, 196, 232] : [150, 192, 226];",
      "  var skyBot = sad ? [196, 200, 208] : [196, 222, 240];",
      "  ctx.fillStyle = f.rgb(skyTop, 1); ctx.fillRect(0, 0, W, H * 0.62);",
      "  ctx.fillStyle = f.rgb(skyBot, 1); ctx.fillRect(0, H * 0.62, W, H * 0.38);",
      "  // 远处云",
      "  for (var c = 0; c < 4; c++) {",
      "    var cw = W * (0.22 + f.hash(c) * 0.2);",
      "    f.ellipse(W * (0.1 + c * 0.28) + Math.sin(t * 0.2 + c) * W * 0.02, H * (0.12 + f.hash(c * 3) * 0.18), cw, cw * 0.28, pal.light, 0.55);",
      "  }",
      "  // 雨",
      "  if (sad) { for (var r = 0; r < 60; r++) { var rx = (f.hash(r * 5.1) * W + t * 40) % W; var ry = (f.hash(r * 9.3) * H + t * 260) % H; f.line(rx, ry, rx - 3, ry + 12, [220, 228, 238], 1, 0.35); } }",
      "  // 草地圆丘",
      "  f.ellipse(W * 0.5, H * 0.92, W * 0.72, H * 0.42, sad ? [96, 122, 96] : [126, 178, 96], 1);",
      "  for (var g = 0; g < 26; g++) { var gx = W * (0.16 + g * 0.028); var gy = H * (0.63 + Math.sin(g * 0.7) * 0.02); f.line(gx, gy + H * 0.02, gx - W * 0.004, gy - H * 0.03, [40, 70, 40], 1.5, 0.55); }",
      "  var bob = Math.sin(t * 2.2) * H * 0.006 + pulse * H * 0.004;",
      "  var near = sad ? 0.72 : 0.78;",
      "  // 左角色（橙）",
      "  f.rect(W * 0.34, H * 0.62 + bob, W * 0.14, H * 0.17, [224, 130, 66], 1);",
      "  f.rect(W * 0.34, H * 0.62 + bob, W * 0.14, H * 0.05, [196, 106, 52], 0.6);",
      "  for (var l1 = 0; l1 < 3; l1++) f.rect(W * (0.355 + l1 * 0.045), H * 0.79 + bob, W * 0.012, H * 0.05, [196, 106, 52], 1);",
      "  f.line(W * 0.34, H * 0.68 + bob, W * 0.30, H * 0.72 + bob, [196, 106, 52], W * 0.008, 1);",
      "  // 右角色（粉）",
      "  f.rect(W * 0.52, H * 0.62 + bob, W * 0.14, H * 0.17, [238, 150, 172], 1);",
      "  f.rect(W * 0.52, H * 0.62 + bob, W * 0.14, H * 0.05, [212, 120, 144], 0.6);",
      "  for (var l2 = 0; l2 < 3; l2++) f.rect(W * (0.535 + l2 * 0.045), H * 0.79 + bob, W * 0.012, H * 0.05, [212, 120, 144], 1);",
      "  f.line(W * 0.66, H * 0.68 + bob, W * 0.70, H * 0.72 + bob, [212, 120, 144], W * 0.008, 1);",
      "  // 蝴蝶结",
      "  f.circle(W * 0.66, H * 0.60 + bob, W * 0.012, [230, 120, 150], 1);",
      "  // 表情：眼 + 嘴（开心 ^ ^ / 难过 - -）",
      "  f.line(W * 0.375, H * 0.665 + bob, W * 0.395, H * 0.655 + bob, [60, 40, 30], 2.5, 1);",
      "  f.line(W * 0.395, H * 0.655 + bob, W * 0.415, H * 0.665 + bob, [60, 40, 30], 2.5, 1);",
      "  f.line(W * 0.565, H * 0.665 + bob, W * 0.585, H * 0.655 + bob, [60, 40, 30], 2.5, 1);",
      "  f.line(W * 0.585, H * 0.655 + bob, W * 0.605, H * 0.665 + bob, [60, 40, 30], 2.5, 1);",
      "  if (happy) { f.line(W * 0.385, H * 0.70 + bob, W * 0.405, H * 0.705 + bob, [60, 40, 30], 2, 0.8); f.line(W * 0.405, H * 0.705 + bob, W * 0.425, H * 0.70 + bob, [60, 40, 30], 2, 0.8); }",
      "  else { f.line(W * 0.375, H * 0.705 + bob, W * 0.415, H * 0.705 + bob, [60, 40, 30], 2, 0.7); }",
      "  // 雨伞 / 阴云（灰暗时）",
      "  if (sad) {",
      "    f.line(W * 0.60, H * 0.60 + bob, W * 0.60, H * 0.44 + bob, [70, 50, 40], 3, 1);",
      "    f.ellipse(W * 0.60, H * 0.44 + bob, W * 0.11, H * 0.05, [240, 190, 70], 1);",
      "  } else if (happy) {",
      "    f.glow(W * 0.82, H * 0.16, H * 0.1, [255, 240, 180], 0.5);",
      "    f.circle(W * 0.82, H * 0.16, H * 0.035, [255, 238, 170], 0.95);",
      "  }",
      "}",
      "function sea(a) {",
      "  var sky = [128, 106, 176];",
      "  ctx.fillStyle = f.rgb(sky, 1); ctx.fillRect(0, 0, W, H * 0.55);",
      "  for (var i = 0; i < 40; i++) f.circle(f.hash(i * 3.1) * W, f.hash(i * 7.7) * H * 0.5, 0.8 + f.hash(i) * 1.2, [230, 230, 255], 0.5);",
      "  var mx = W * 0.5, my = H * 0.33;",
      "  f.glow(mx, my, H * 0.2, [255, 244, 214], 0.45);",
      "  f.circle(mx, my, H * 0.085 * (1 + 0.02 * Math.sin(t * 1.5)), [255, 246, 220], 1);",
      "  // 波浪（三层）",
      "  var cols = [[150, 210, 235], [120, 186, 224], [86, 150, 200]];",
      "  for (var b = 0; b < 3; b++) {",
      "    ctx.beginPath();",
      "    var y0 = H * (0.55 + b * 0.08);",
      "    ctx.moveTo(0, y0);",
      "    for (var x = 0; x <= W; x += W / 24) ctx.lineTo(x, y0 + Math.sin(x / W * 6 + t * (1.0 + b * 0.3) + b) * H * 0.018);",
      "    ctx.lineTo(W, H); ctx.lineTo(0, H); ctx.closePath();",
      "    ctx.fillStyle = f.rgb(cols[b], 1); ctx.fill();",
      "  }",
      "}",
      "function drawMotif(id, a) {",
      "  if (id === 'pal') pal(a);",
      "  else if (id === 'sea') sea(a);",
      "  else if (id === 'night') night(a);",
      "  else if (id === 'water') water(a);",
      "  else if (id === 'wind') wind(a);",
      "  else if (id === 'light') light(a);",
      "  else if (id === 'nature') nature(a);",
      "  else if (id === 'memory') memory(a);",
      "  else city(a);",
      "}",
      "var cur = motifs[((idx % motifs.length) + motifs.length) % motifs.length] || 'city';",
      "var prev = motifs[((idx - 1) % motifs.length + motifs.length) % motifs.length] || cur;",
      "f.camera(W / 2 + cam.x, H / 2 + cam.y, breath * (1 + lp * 0.03 + bass * 0.02), 0, function () {",
      "  drawMotif(cur, 1);",
      "  if (lp < 0.4 && line && line.index > 0) {",
      "    ctx.save(); ctx.globalAlpha = 1 - lp / 0.4; drawMotif(prev, 1); ctx.restore();",
      "  }",
      "});",
      "f.noise(80, { color: [255, 255, 255], alpha: 0.02, size: 1 });",
      "if (pulse > 0.82) f.glow(W * 0.5, H * 0.5, W * 0.9, pal.light, pulse * 0.06);",
      "f.vignette(0.6 - 0.06 * pulse);"
    ].join("\\n");
  }

  NS.mvAuto = {
    motifFor: motifFor,
    build: build
  };
})(window.CodeMV);
